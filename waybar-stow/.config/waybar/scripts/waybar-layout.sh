#!/usr/bin/env bash
# Waybar layout selector.
#
# A *layout* is a directory under ~/.config/waybar/configs/<name>/ holding a
# `config` and a `style.css`. The active layout is tracked by the symlink
# ~/.config/waybar/configs/current. The generated ~/.config/waybar/style.css is
# themes/current.css (colour theme) + configs/<layout>/style.css (layout).
#
# Usage:
#   waybar-layout.sh                      rofi menu
#   waybar-layout.sh <layout>             switch to layout
#   waybar-layout.sh apply <layout> [--no-restart]
#   waybar-layout.sh apply-for-theme <theme> [--no-restart]
#   waybar-layout.sh --list | --current | --for-theme <theme> | --help

set -euo pipefail

WB="$HOME/.config/waybar"
CONFIGS="$WB/configs"
THEMES="$WB/themes"
CURRENT="$CONFIGS/current"
ROFI_CONFIG="$HOME/.config/rofi/theme-menu.rasi"
ROFI_OVERRIDES="$HOME/.config/rofi/theme-overrides.rasi"

list_layouts() {
  find "$CONFIGS" -mindepth 1 -maxdepth 1 -type d ! -name current -printf '%f\n' | sort
}

current_layout() {
  if [[ -L "$CURRENT" ]]; then
    basename "$(readlink -f "$CURRENT")"
  else
    echo "default"
  fi
}

current_theme() {
  if [[ -L "$THEMES/current.css" ]]; then
    basename "$(readlink "$THEMES/current.css")" .css
  fi
}

# Layout to use when switching to a colour theme:
#  - a layout named after the theme (bsod, platinum, ...) wins,
#  - otherwise keep a standalone layout (one not tied to any theme) if active,
#  - otherwise fall back to default.
layout_for_theme() {
  local theme="$1" cur
  if [[ -d "$CONFIGS/$theme" ]]; then
    echo "$theme"; return
  fi
  cur=$(current_layout)
  if [[ -d "$CONFIGS/$cur" && ! -f "$THEMES/$cur.css" ]]; then
    echo "$cur"; return
  fi
  echo "default"
}

layout_position() {
  grep -o '"position": *"[^"]*"' "$CONFIGS/$1/config" 2>/dev/null | head -1 | grep -o '"[^"]*"$' | tr -d '"'
}

# rofi overrides for bottom bars (menus anchor south, square corners)
write_rofi_overrides() {
  if [[ "$(layout_position "$1")" == "bottom" ]]; then
    cat > "$ROFI_OVERRIDES" <<'RASI'
/* Auto-generated by waybar-layout.sh — bottom bar overrides */
window { location: south; anchor: south; y-offset: -10px; border-radius: 0; }
inputbar { border-radius: 0; }
listview { border-radius: 0; }
element { border-radius: 0; }
RASI
  else
    echo '/* Auto-generated by waybar-layout.sh — no overrides */' > "$ROFI_OVERRIDES"
  fi
}

rofi_override_args() {
  if [[ "$(layout_position "$(current_layout)")" == "bottom" ]]; then
    echo '-theme-str "window { location: south; anchor: south; y-offset: -10px; border-radius: 0; } element { border-radius: 0; } inputbar { border-radius: 0; } listview { border-radius: 0; }"'
  fi
}

restart_waybar() {
  pkill -x waybar 2>/dev/null || true
  sleep 0.3
  setsid -f waybar >/dev/null 2>&1
}

apply_layout() {
  local layout="$1" restart="${2:-yes}" theme
  if [[ ! -f "$CONFIGS/$layout/config" || ! -f "$CONFIGS/$layout/style.css" ]]; then
    echo "waybar-layout: layout '$layout' not found in $CONFIGS" >&2
    return 1
  fi

  ln -sfn "$CONFIGS/$layout" "$CURRENT"

  theme=$(current_theme || true)
  if [[ -n "$theme" && -f "$THEMES/$theme.css" ]]; then
    cat "$THEMES/$theme.css" "$CONFIGS/$layout/style.css" > "$WB/style.css"
  else
    cp "$CONFIGS/$layout/style.css" "$WB/style.css"
  fi
  cp "$CONFIGS/$layout/config" "$WB/config"
  write_rofi_overrides "$layout"

  if [[ "$restart" == "yes" ]]; then
    restart_waybar
    notify-send "󰍜 Waybar" "$layout" -t 2000 2>/dev/null || true
  fi
}

menu() {
  local cur entries="" layout selected overrides
  cur=$(current_layout)
  for layout in $(list_layouts); do
    if [[ "$layout" == "$cur" ]]; then
      entries+="󰸞  $layout\n"
    else
      entries+="󰍜  $layout\n"
    fi
  done
  overrides=$(rofi_override_args)
  selected=$(echo -e "$entries" | sed '/^$/d' \
    | eval rofi -dmenu -i -p '"Bar"' -config '"$ROFI_CONFIG"' $overrides \
        -theme-str '"window { width: 280px; } listview { lines: 9; }"') || true
  [[ -z "$selected" ]] && return 0
  layout=$(echo "$selected" | sed 's/^[^ ]* *//')
  [[ "$layout" == "$cur" ]] && return 0
  apply_layout "$layout"
}

usage() {
  sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
}

case "${1:-}" in
  "")                 menu ;;
  --help|-h)          usage ;;
  --list|-l)          list_layouts ;;
  --current|-c)       current_layout ;;
  --for-theme)        layout_for_theme "${2:?theme name required}" ;;
  apply)
    [[ "${3:-}" == "--no-restart" ]] && r=no || r=yes
    apply_layout "${2:?layout name required}" "$r" ;;
  apply-for-theme)
    [[ "${3:-}" == "--no-restart" ]] && r=no || r=yes
    apply_layout "$(layout_for_theme "${2:?theme name required}")" "$r" ;;
  *)                  apply_layout "$1" ;;
esac
